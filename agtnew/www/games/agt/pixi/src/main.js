    dec2Bin(n, length = 5) {
        let b = Number(n).toString(2);   // преобразуем в двоичное
        if (b.length > length) {
            b = b.slice(-length);             // обрезаем слева
        } else {
            b = b.padStart(length, "0");      // добавляем нули слева
        }
        return b;
    },

