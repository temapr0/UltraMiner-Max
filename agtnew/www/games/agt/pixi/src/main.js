    createCoinFountain(screen, options = {}) {
        const {
            spawnIntervalMs = 150,
            spawnPerTick = 2,

            minSpeedY = 25,
            maxSpeedY = 35,
            spreadX = 16,
            gravity = 0.5,

            startX = this.gameWidth / 2,
            startY = this.gameHeight + 50,

            maxCoins = 300
        } = options;

        const coins = [];
        let spawning = true;
        let timerId = null;

        const spawn = () => {
            if (!spawning) return;

            for (let i = 0; i < spawnPerTick; i++) {
                if (coins.length >= maxCoins) break;

                const coin = this.getFlyCoin();

                coin.x = startX + (Math.random() - 0.5) * 40; // небольшая «горловина»
                coin.y = startY;

                coin.vx = (Math.random() - 0.5) * spreadX;
                coin.vy = -(minSpeedY + Math.random() * (maxSpeedY - minSpeedY));

                screen.addChild(coin);
                coins.push(coin);
            }

            timerId = setTimeout(spawn, spawnIntervalMs);
        };

        const animate = () => {
            for (let i = coins.length - 1; i >= 0; i--) {
                const c = coins[i];

                c.vy += gravity;
                c.x += c.vx;
                c.y += c.vy;
                c.rotation += 0.2;

                if (c.y > this.gameHeight + 120) {
                    screen.removeChild(c);
                    c.destroy();
                    coins.splice(i, 1);
                }
            }

            if (spawning || coins.length > 0) {
                requestAnimationFrame(animate);
            }
        };

        spawn();
        requestAnimationFrame(animate);

        return {
            stop() {
                spawning = false;
                if (timerId) {
                    clearTimeout(timerId);
                    timerId = null;
                }
            },
            destroy() {
                spawning = false;
                if (timerId) {
                    clearTimeout(timerId);
                    timerId = null;
                }
                for (let i = coins.length - 1; i >= 0; i--) {
                    const c = coins[i];
                    screen.removeChild(c);
                    c.destroy();
                }
                coins.length = 0;
            }
        };
    },

    spawnFlyCoins(container, opts = {}) {
        const {
            x, y,
            x1, y1,

            count = 50,

            // speed: px/sec
            speed = 200,

            // страховка: даже если dist маленький/нулевой — полёт не будет мгновенным
            minDuration = 0.6,   // сек
            maxDuration = 2.5,   // сек (опционально, чтобы не улетало в вечность)

            jitterStart = 0,
            jitterEnd = 0,

            arcHeight = 1000,
            arcJitter = 60,

            lifeJitter = 0.5,
            delaySpread = 2,

            alphaFrom = null,
            alphaTo = null,
            scaleFrom = null,
            scaleTo = null,
            rotateByVelocity = true
        } = opts;

        if (!container) return;

        const app = (this.app || PIXI.Application?.sharedApplication || null);
        const ticker = (app && app.ticker) ? app.ticker : (PIXI.Ticker && PIXI.Ticker.shared ? PIXI.Ticker.shared : null);
        if (!ticker) return;

        const rand = (a, b) => a + Math.random() * (b - a);
        const lerp = (a, b, t) => a + (b - a) * t;

        const quadBezier = (p0, p1, p2, t) => {
            const it = 1 - t;
            return (it * it) * p0 + 2 * it * t * p1 + (t * t) * p2;
        };

        const destroyCoin = (coin) => {
            if (!coin) return;
            if (coin.parent) coin.parent.removeChild(coin);
            if (coin.destroy) coin.destroy({ children: true, texture: false, baseTexture: false });
        };

        // валидация координат (если где-то undefined — получишь странности)
        if (![x, y, x1, y1].every(Number.isFinite)) return;

        const dx0 = x1 - x;
        const dy0 = y1 - y;
        let dist = Math.sqrt(dx0 * dx0 + dy0 * dy0);

        // если dist == 0 — всё равно дадим полёт (иначе мгновенная смерть)
        if (!Number.isFinite(dist) || dist < 1) dist = 1;

        let baseDuration = (speed > 0) ? (dist / speed) : 1.0;
        if (!Number.isFinite(baseDuration) || baseDuration <= 0) baseDuration = 1.0;

        // clamp
        if (baseDuration < minDuration) baseDuration = minDuration;
        if (maxDuration !== null && baseDuration > maxDuration) baseDuration = maxDuration;

        const coins = [];

        for (let i = 0; i < count; i++) {
            const coin = this.getFlyCoin(0.15);
            if (!coin) continue;

            const sx = x + rand(-jitterStart, jitterStart);
            const sy = y + rand(-jitterStart, jitterStart);
            const ex = x1 + rand(-jitterEnd, jitterEnd);
            const ey = y1 + rand(-jitterEnd, jitterEnd);

            const midx = (sx + ex) * 0.5;
            const midy = (sy + ey) * 0.5;

            const arc = arcHeight + rand(-arcJitter, arcJitter);
            const cx = midx + rand(-arcJitter, arcJitter) * 0.35;
            const cy = midy - arc;

            let dur = baseDuration * rand(1 - lifeJitter, 1 + lifeJitter);
            if (dur < minDuration) dur = minDuration;
            if (maxDuration !== null && dur > maxDuration) dur = maxDuration;

            const delay = rand(0, delaySpread);

            coin.x = sx;
            coin.y = sy;

            if (alphaFrom !== null) coin.alpha = alphaFrom;
            if (scaleFrom !== null) coin.scale.set(scaleFrom);

            container.addChild(coin);

            coins.push({
                coin,
                sx, sy, cx, cy, ex, ey,
                d: dur,
                t: 0,
                delay
            });
        }

        // независимое время: без delta/deltaMS
        let lastMs = performance.now();

        const tickFn = () => {
            const nowMs = performance.now();
            const dt = (nowMs - lastMs) / 1000;
            lastMs = nowMs;

            for (let i = coins.length - 1; i >= 0; i--) {
                const c = coins[i];

                if (c.delay > 0) {
                    c.delay -= dt;
                    continue;
                }

                c.t += dt;

                let p = c.t / c.d;
                if (p < 0) p = 0;
                if (p > 1) p = 1;

                const nx = quadBezier(c.sx, c.cx, c.ex, p);
                const ny = quadBezier(c.sy, c.cy, c.ey, p);

                c.coin.x = nx;
                c.coin.y = ny;

                if (rotateByVelocity && c.coin.rotation !== undefined) {
                    const p2 = (p < 0.98) ? (p + 0.02) : p;
                    const nx2 = quadBezier(c.sx, c.cx, c.ex, p2);
                    const ny2 = quadBezier(c.sy, c.cy, c.ey, p2);
                    c.coin.rotation = Math.atan2(ny2 - ny, nx2 - nx);
                }

                if (alphaFrom !== null && alphaTo !== null) {
                    c.coin.alpha = lerp(alphaFrom, alphaTo, p);
                }
                if (scaleFrom !== null && scaleTo !== null) {
                    const s = lerp(scaleFrom, scaleTo, p);
                    c.coin.scale.set(s);
                }

                if (p >= 1) {
                    destroyCoin(c.coin);
                    coins.splice(i, 1);
                }
            }

            if (coins.length === 0) {
                ticker.remove(tickFn);
            }
        };

        ticker.add(tickFn);
    },

