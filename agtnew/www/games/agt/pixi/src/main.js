    bindButtonMicroAnim(btn, opts = {}) {
        const target = opts.target ?? btn;
        const ticker = opts.ticker ?? PIXI.Ticker.shared;

        const hoverScale = opts.hoverScale ?? 1.02;
        const downScale  = opts.downScale  ?? 0.95;

        const hoverX = opts.hoverX ?? 0;
        const hoverY = opts.hoverY ?? -1;

        const downX = opts.downX ?? 0;
        const downY = opts.downY ?? 1;

        const duration = opts.duration ?? 180;

        const useDesktopHover = opts.useDesktopHover ?? true;
        const isHoverDevice = useDesktopHover
            ? window.matchMedia('(hover: hover) and (pointer: fine)').matches
            : true;

        let baseScaleX = target.scale.x;
        let baseScaleY = target.scale.y;
        let baseX = target.x;
        let baseY = target.y;

        let isDown = false;
        let isDisabled = false;

        let currentMul = 1;
        let currentDx = 0;
        let currentDy = 0;

        let targetMul = 1;
        let targetDx = 0;
        let targetDy = 0;

        const setTargetState = (mul, dx, dy) => {
            targetMul = mul;
            targetDx = dx;
            targetDy = dy;
        };

        const syncNow = () => {
            currentMul = targetMul;
            currentDx = targetDx;
            currentDy = targetDy;

            target.scale.set(baseScaleX * currentMul, baseScaleY * currentMul);
            target.x = baseX + currentDx;
            target.y = baseY + currentDy;
        };

        const toIdle = () => {
            setTargetState(1, 0, 0);
        };

        const toHover = () => {
            setTargetState(hoverScale, hoverX, hoverY);
        };

        const toDown = () => {
            setTargetState(downScale, downX, downY);
        };

        const update = (tickerObj) => {
            const dtMs = (tickerObj.deltaMS && isFinite(tickerObj.deltaMS)) ? tickerObj.deltaMS : 16.6667;
            const k = 1 - Math.pow(0.001, dtMs / duration);

            currentMul += (targetMul - currentMul) * k;
            currentDx += (targetDx - currentDx) * k;
            currentDy += (targetDy - currentDy) * k;

            target.scale.set(baseScaleX * currentMul, baseScaleY * currentMul);
            target.x = baseX + currentDx;
            target.y = baseY + currentDy;
        };

        const onPointerOver = () => {
            if (isDisabled || isDown || !isHoverDevice) return;
            toHover();
        };

        const onPointerOut = () => {
            if (isDisabled || isDown) return;
            toIdle();
        };

        const onPointerDown = () => {
            if (isDisabled) return;
            isDown = true;
            toDown();
        };

        const onPointerUp = () => {
            if (isDisabled) return;
            isDown = false;
            if (isHoverDevice) {
                toHover();
            } else {
                toIdle();
            }
        };

        const onPointerUpOutside = () => {
            if (isDisabled) return;
            isDown = false;
            toIdle();
        };

        const onPointerCancel = () => {
            if (isDisabled) return;
            isDown = false;
            toIdle();
        };

        btn.eventMode = btn.eventMode || 'static';
        btn.cursor = btn.cursor || 'pointer';

        btn.on('pointerover', onPointerOver);
        btn.on('pointerout', onPointerOut);
        btn.on('pointerdown', onPointerDown);
        btn.on('pointerup', onPointerUp);
        btn.on('pointerupoutside', onPointerUpOutside);
        btn.on('pointercancel', onPointerCancel);

        ticker.add(update);
        toIdle();
        syncNow();

        btn.microAnim = {
            reset() {
                isDown = false;
                toIdle();
            },

            hover() {
                if (isDisabled) return;
                isDown = false;
                toHover();
            },

            press() {
                if (isDisabled) return;
                isDown = true;
                toDown();
            },

            disable(value = true) {
                isDisabled = !!value;
                isDown = false;
                toIdle();
            },

            syncBase() {
                baseScaleX = target.scale.x / currentMul;
                baseScaleY = target.scale.y / currentMul;
                baseX = target.x - currentDx;
                baseY = target.y - currentDy;
            },

            destroy() {
                btn.off('pointerover', onPointerOver);
                btn.off('pointerout', onPointerOut);
                btn.off('pointerdown', onPointerDown);
                btn.off('pointerup', onPointerUp);
                btn.off('pointerupoutside', onPointerUpOutside);
                btn.off('pointercancel', onPointerCancel);
                ticker.remove(update);
            }
        };

        return btn;
    },














